const assert=require('node:assert/strict');
const {safePageCuts}=require('../js/pdf-share.js');
const ranges=[{top:95,bottom:110},{top:188,bottom:230},{top:270,bottom:295},{top:285,bottom:310}];
const cuts=safePageCuts(420,100,ranges);
assert.deepEqual(cuts,[0,95,188,270,370,420]);
for(const cut of cuts.slice(1,-1))assert.ok(!ranges.some(range=>range.top<cut&&range.bottom>cut),'Oldalhatár nem vághat betűbe vagy fejlécbe.');
assert.equal(cuts.slice(1).reduce((sum,end,index)=>sum+end-cuts[index],0),420,'Minden forráspixel pontosan egyszer marad meg.');
const longParagraph=[{top:0,bottom:240},...Array.from({length:12},(_,i)=>({top:i*20+5,bottom:i*20+16}))];
const longCuts=safePageCuts(250,100,longParagraph);
for(const cut of longCuts.slice(1,-1))assert.ok(!longParagraph.slice(1).some(range=>range.top<cut&&range.bottom>cut),'Egy oldalnál hosszabb leírás csak sorok között törhető.');
assert.deepEqual(safePageCuts(50,100,[]),[0,50],'Nem keletkezhet üres első oldal.');
assert.throws(()=>safePageCuts(50,0,[]),/oldalmérete hibás/,'Hibás méretnél nem szabad végtelen ciklusba kerülni.');
console.log('Biztonságos PDF-oldalhatárok: betűk, fejléc, hosszú leírás, teljes pixelmegőrzés: OK');
